#!/usr/bin/env python3
"""Crop Kantongin asset sheets into categorized PNGs and generate an Expo registry."""
from __future__ import annotations
import argparse, json, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MANIFESTS = {
    "illustrations": ROOT / "tools" / "assets_manifest_illustrations.json",
    "app-ui": ROOT / "tools" / "assets_manifest_app_ui.json",
}

def slugify(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", value.strip().lower()).strip("_")

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sheet", choices=MANIFESTS.keys(), required=True,
                        help="Pilih illustrations untuk Sheet-2 atau app-ui untuk Sheet-1.")
    parser.add_argument("--input", required=True, help="Path asset sheet PNG/JPG/WebP.")
    parser.add_argument("--output", default=str(ROOT / "assets" / "generated"))
    parser.add_argument("--remove-background", action="store_true",
                        help="Opsional: gunakan rembg pada aset yang ditandai di manifest.")
    args = parser.parse_args()
    source_path = Path(args.input).resolve()
    manifest_path = MANIFESTS[args.sheet]
    output_root = Path(args.output).resolve()
    if not source_path.exists():
        print(f"File sumber tidak ditemukan: {source_path}", file=sys.stderr); return 2
    if not manifest_path.exists():
        print(f"Manifest tidak ditemukan: {manifest_path}", file=sys.stderr); return 2
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    with Image.open(source_path) as im:
        source = im.convert("RGBA")
    w, h = source.size
    exported = []
    for item in manifest["assets"]:
        name, category = slugify(item["name"]), slugify(item["category"])
        l,t,r,b = item["box"]
        if not (0 <= l < r <= 1 and 0 <= t < b <= 1):
            print(f"Box tidak valid untuk {name}: {item['box']}", file=sys.stderr); return 2
        crop = source.crop((int(l*w), int(t*h), int(r*w), int(b*h)))
        if args.remove_background and item.get("remove_background", False):
            try:
                from rembg import remove
                result = remove(crop)
                if not isinstance(result, Image.Image):
                    from io import BytesIO
                    result = Image.open(BytesIO(result))
                crop = result.convert("RGBA")
            except ImportError:
                print("Untuk hapus latar, install dulu: python -m pip install rembg", file=sys.stderr)
                return 3
        folder = output_root / category
        folder.mkdir(parents=True, exist_ok=True)
        dest = folder / f"{name}.png"
        crop.save(dest, "PNG", optimize=True)
        rel = dest.relative_to(output_root).with_suffix("").as_posix()
        exported.append((name, rel))
        print(f"✓ {category}/{name}.png ({crop.width}x{crop.height})")
    # Create a static registry for all generated assets, including files from
    # earlier sheet runs that share this output directory. Include the folder
    # in each export name so same-named assets from different categories stay
    # distinct.
    index = output_root / "index.ts"
    lines = ["// Generated by tools/split_assets.py. Edit the manifest and rerun.", ""]
    for asset_path in sorted(output_root.rglob("*.png")):
        rel = asset_path.relative_to(output_root).with_suffix("").as_posix()
        parts = re.split(r"[^a-zA-Z0-9]+", rel)
        var = "".join(p.title() for p in parts if p)
        var = var[:1].lower() + var[1:]
        lines.append(f"export const {var} = require('./{rel}.png');")
    lines.append("")
    index.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nSelesai. {len(exported)} crop disimpan ke {output_root}")
    print(f"Registry: {index}")
    print("PENTING: ini crop awal. Periksa preview; sesuaikan bounding box bila label/background ikut terpotong.")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
